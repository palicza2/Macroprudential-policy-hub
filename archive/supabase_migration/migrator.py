if __name__ == "__main__":
    # Example usage
    import sys
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(name)s - %(levelname)s - %(message)s')
    
    try:
        migrator = SupabaseMigrator()
        
        # Dry run first
        print("\n=== DRY RUN ===")
        results = migrator.migrate_all(validate=True, dry_run=True)
        print(f"Dry run results: {results}")
        
        # Ask for confirmation
        response = input("\nProceed with actual migration? (yes/no): ")
        if response.lower() == "yes":
            print("\n=== ACTUAL MIGRATION ===")
            results = migrator.migrate_all(validate=True, dry_run=False)
            print(f"Migration results: {results}")
        else:
            print("Migration cancelled.")
            
    except Exception as e:
        logger.error(f"Migration failed: {e}")
        sys.exit(1)
